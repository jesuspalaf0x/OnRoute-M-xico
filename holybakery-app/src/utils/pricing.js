export function getZoneAndPrice(lat, lng) {
  const pt = {
    type: 'Feature',
    geometry: {
      type: 'Point',
      coordinates: [lng, lat]
    }
  };

  for (const feature of mapData.features) {
    if (feature.geometry.type === 'Polygon' || feature.geometry.type === 'MultiPolygon') {
      if (booleanPointInPolygon(pt, feature)) {
        const zoneName = feature.properties['Nombres de cuadrantes'];
        return {
          zone: zoneName,
          price: prices[zoneName] || null
        };
      }
    }
  }

  return { zone: 'Fuera de rango', price: null };
}
